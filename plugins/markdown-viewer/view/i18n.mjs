export function normalizeLocale(rawLocale) {
  const s = String(rawLocale || "").trim().toLowerCase();
  if (!s || s === "auto") return "auto";
  if (s.startsWith("en")) return "en";
  if (s.startsWith("zh")) return "zh-CN";
  return "en";
}

export function resolveEffectiveLocale(preference, hostLocale) {
  const norm = normalizeLocale(preference);
  if (norm === "zh-CN" || norm === "en") return norm;
  const candidate = hostLocale || (typeof navigator !== "undefined" ? navigator.language : "zh-CN");
  return String(candidate || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale, key, fallback = "") {
  const eff = locale === "en" ? "en" : "zh-CN";
  return MESSAGES[eff][key] ?? MESSAGES["zh-CN"][key] ?? fallback;
}

export function applyI18n(doc, locale) {
  if (!doc || typeof doc.querySelectorAll !== "function") return;
  const eff = locale === "en" ? "en" : "zh-CN";
  doc.documentElement.lang = eff;

  for (const node of doc.querySelectorAll("[data-i18n]")) {
    const key = node.dataset.i18n;
    const text = translate(eff, key);
    if (!text) continue;
    const kbd = node.querySelector && node.querySelector(".kbd");
    const count = node.querySelector && node.querySelector(".scope-count");
    if (kbd || count) {
      const child = kbd || count;
      node.textContent = text + " ";
      node.appendChild(child);
    } else {
      node.textContent = text;
    }
  }
  for (const node of doc.querySelectorAll("[data-i18n-placeholder]")) {
    const text = translate(eff, node.dataset.i18nPlaceholder);
    if (text) node.placeholder = text;
  }
  for (const node of doc.querySelectorAll("[data-i18n-title]")) {
    const text = translate(eff, node.dataset.i18nTitle);
    if (text) node.title = text;
  }
  for (const node of doc.querySelectorAll("[data-i18n-tooltip]")) {
    const text = translate(eff, node.dataset.i18nTooltip);
    if (text) node.dataset.tooltip = text;
  }
}
